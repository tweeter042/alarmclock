package io.github.tweeter042.alarmclock.core.designsystem.icon

import android.content.Context
import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.drawable.AdaptiveIconDrawable
import android.graphics.drawable.Drawable
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import io.github.tweeter042.alarmclock.core.designsystem.R
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.annotation.Config
import org.robolectric.annotation.GraphicsMode
import java.io.File

/**
 * Inflates every launcher, alternate, splash and notification drawable through the real Android
 * VectorDrawable renderer and checks a few pixels of the artwork. The drawables are generated by
 * art/icon/source/deliver.js; a malformed path or gradient would otherwise only fail on a device.
 * PNGs go to build/screenshots-out/launcher-icons/ for visual comparison with art/icon.
 */
@RunWith(AndroidJUnit4::class)
@GraphicsMode(GraphicsMode.Mode.NATIVE)
@Config(sdk = [35])
class LauncherIconRenderTest {

    private val context: Context = ApplicationProvider.getApplicationContext()
    private val px = 432 // 4 px per viewport unit

    private fun render(id: Int, name: String, size: Int = px): Bitmap {
        val drawable: Drawable = checkNotNull(context.getDrawable(id)) { "$name did not inflate" }
        val bitmap = Bitmap.createBitmap(size, size, Bitmap.Config.ARGB_8888)
        drawable.setBounds(0, 0, size, size)
        drawable.draw(Canvas(bitmap))
        val dir = File("build/screenshots-out/launcher-icons").apply { mkdirs() }
        File(dir, "$name.png").outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
        return bitmap
    }

    /** Pixel at viewport coordinates (108-unit canvas). */
    private fun Bitmap.at(x: Double, y: Double): Int = getPixel((x * width / 108).toInt(), (y * height / 108).toInt())

    private fun assertOpaque(c: Int, what: String) = assertEquals("$what alpha", 255, Color.alpha(c))

    private fun assertTransparent(c: Int, what: String) = assertEquals("$what alpha", 0, Color.alpha(c))

    @Test
    fun backgroundsAreFullBleed() {
        for ((id, name) in listOf(
            R.drawable.ic_launcher_background to "ic_launcher_background",
            R.drawable.ic_launcher_alt_midnight_background to "ic_launcher_alt_midnight_background",
            R.drawable.ic_launcher_alt_daylight_background to "ic_launcher_alt_daylight_background",
            R.drawable.ic_launcher_alt_neon_background to "ic_launcher_alt_neon_background",
        )) {
            val b = render(id, name)
            for ((x, y) in listOf(0.5 to 0.5, 107.5 to 0.5, 54.0 to 54.0, 0.5 to 107.5, 107.5 to 107.5)) {
                assertOpaque(b.at(x, y), "$name ($x, $y)")
            }
        }
    }

    @Test
    fun foregroundsKeepTheMotifInsideTheSafeZone() {
        for ((id, name) in listOf(
            R.drawable.ic_launcher_foreground to "ic_launcher_foreground",
            R.drawable.ic_launcher_alt_midnight_foreground to "ic_launcher_alt_midnight_foreground",
            R.drawable.ic_launcher_alt_daylight_foreground to "ic_launcher_alt_daylight_foreground",
            R.drawable.ic_launcher_alt_neon_foreground to "ic_launcher_alt_neon_foreground",
        )) {
            val b = render(id, name)
            // corners of the canvas and the area outside the 72-unit viewport are transparent
            for ((x, y) in listOf(2.0 to 2.0, 106.0 to 2.0, 2.0 to 106.0, 106.0 to 106.0, 54.0 to 12.0, 54.0 to 100.0)) {
                assertTransparent(b.at(x, y), "$name ($x, $y)")
            }
            // bezel, dial centre (pivot), sky above the hands and sea below them are painted
            for ((x, y) in listOf(54.0 to 32.4, 54.0 to 55.8, 44.0 to 45.0, 60.0 to 70.0)) {
                assertOpaque(b.at(x, y), "$name ($x, $y)")
            }
        }
    }

    @Test
    fun defaultForegroundShowsTheSunriseScene() {
        val b = render(R.drawable.ic_launcher_foreground, "ic_launcher_foreground_scene")
        val sun = b.at(47.0, 57.5) // sun disc left of the hands, just above the horizon (y 59.7)
        val sea = b.at(40.0, 68.0) // sea below the horizon
        val sky = b.at(54.0 - 9.0, 40.0) // indigo/violet sky
        assertTrue("sun is warm: ${Integer.toHexString(sun)}", Color.red(sun) > 230 && Color.green(sun) > 150 && Color.blue(sun) < 160)
        assertTrue("sea is deep violet: ${Integer.toHexString(sea)}", Color.blue(sea) > Color.green(sea) && Color.red(sea) < 140)
        assertTrue("sky is blue-violet: ${Integer.toHexString(sky)}", Color.blue(sky) > Color.green(sky))
        // the horizon is a hard edge: one unit above and below differ strongly
        val above = b.at(36.0, 59.2)
        val below = b.at(36.0, 60.4)
        assertTrue("hard horizon", Color.red(above) - Color.red(below) > 60)
        // cream hands: the minute hand points at 12, the hour hand at 7
        val minute = b.at(54.0, 42.0)
        val hour = b.at(50.8, 61.2)
        for ((c, what) in listOf(minute to "minute hand", hour to "hour hand")) {
            assertTrue("$what is cream: ${Integer.toHexString(c)}", Color.red(c) > 240 && Color.green(c) > 230 && Color.blue(c) > 210)
        }
    }

    @Test
    fun monochromeIsSingleColourWithATwoToneSky() {
        val b = render(R.drawable.ic_launcher_monochrome, "ic_launcher_monochrome")
        val ring = b.at(54.0, 55.51 - 19.5)
        val sky = b.at(46.0, 46.0)
        val face = b.at(46.0, 66.0)
        assertOpaque(ring, "ring")
        assertTrue("sky is translucent: ${Color.alpha(sky)}", Color.alpha(sky) in 60..85)
        assertTransparent(face, "lower face")
        assertTransparent(b.at(10.0, 10.0), "outside")
    }

    @Test
    fun adaptiveIconsInflateWithMonochrome() {
        for ((id, name) in listOf(
            R.mipmap.ic_launcher to "ic_launcher",
            R.mipmap.ic_launcher_round to "ic_launcher_round",
            R.mipmap.ic_launcher_alt_midnight to "ic_launcher_alt_midnight",
            R.mipmap.ic_launcher_alt_daylight to "ic_launcher_alt_daylight",
            R.mipmap.ic_launcher_alt_neon to "ic_launcher_alt_neon",
        )) {
            val d = checkNotNull(context.getDrawable(id))
            assertTrue("$name is adaptive", d is AdaptiveIconDrawable)
            assertTrue("$name has a monochrome layer", (d as AdaptiveIconDrawable).monochrome != null)
            val b = render(id, name, 192)
            assertOpaque(b.getPixel(96, 96), "$name centre")
        }
    }

    @Test
    fun splashAndNotificationIcons() {
        val splash = checkNotNull(context.getDrawable(R.drawable.ic_splash_foreground))
        assertEquals(240f * context.resources.displayMetrics.density, splash.intrinsicWidth.toFloat(), 1f)
        render(R.drawable.ic_splash_foreground, "ic_splash_foreground")
        val n = render(R.drawable.ds_ic_notification, "ds_ic_notification", 96)
        assertEquals(24f * context.resources.displayMetrics.density, checkNotNull(context.getDrawable(R.drawable.ds_ic_notification)).intrinsicWidth.toFloat(), 1f)
        var opaque = 0
        for (y in 0 until 96) for (x in 0 until 96) {
            val c = n.getPixel(x, y)
            if (Color.alpha(c) > 0) assertTrue("notification icon is white", Color.red(c) == 255 && Color.green(c) == 255 && Color.blue(c) == 255)
            if (Color.alpha(c) == 255) opaque++
        }
        assertTrue("notification silhouette has substance: $opaque px", opaque > 96 * 96 / 8)
        assertEquals("ds_splash_background", 0xFF212A6A.toInt(), context.getColor(R.color.ds_splash_background))
    }
}
