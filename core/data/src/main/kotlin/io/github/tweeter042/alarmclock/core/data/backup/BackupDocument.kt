/**
 * The backup file (UTF-8 JSON, [ModelJson] conventions). Never contains secrets: tokens live in the
 * SecretStore, which is not part of [AppSettings]. Photo targets carry metadata only (label and the
 * ML labels), not the reference image files.
 *
 * Every section has a default, so a backup from an older app version (or with sections removed by
 * hand) still restores. A missing [settings] section leaves the current settings untouched.
 */
@Serializable
internal data class BackupDocument(
    val format: String,
    val version: Int,
    val createdAt: Long = 0L,
    val appVersion: String = "",
    val settings: AppSettings? = null,
    val alarms: List<Alarm> = emptyList(),
    val groups: List<AlarmGroup> = emptyList(),
    /** CUSTOM and CALENDAR holidays only; BUILT_IN holidays are generated by the app. */
    val holidays: List<Holiday> = emptyList(),
    /** Stored as IDLE: a running timer cannot be resumed meaningfully on another install. */
    val timers: List<TimerModel> = emptyList(),
    val timerPresets: List<TimerPreset> = emptyList(),
    val worldClocks: List<WorldClock> = emptyList(),
    val routineItems: List<MorningRoutineItem> = emptyList(),
    val registeredCodes: List<RegisteredCode> = emptyList(),
    val photoTargets: List<PhotoTarget> = emptyList(),
    val calendarRules: List<CalendarAlarmRule> = emptyList(),
    val locationAlarms: List<LocationAlarm> = emptyList(),
) {
    fun summary(): BackupSummary = BackupSummary(
        alarms = alarms.size,
        groups = groups.size,
        timers = timers.size,
        worldClocks = worldClocks.size,
        holidays = holidays.size,
        other = timerPresets.size + routineItems.size + registeredCodes.size + photoTargets.size +
            calendarRules.size + locationAlarms.size,
        createdAt = createdAt,
        appVersion = appVersion,
    )
}

/** Encodes and strictly validates [BackupDocument]s. */
internal object BackupCodec {
    const val FORMAT = "alarmclock-backup"
    const val VERSION = 1

    /** Backups are tiny (kilobytes); anything this large is not one of ours. */
    const val MAX_BYTES: Int = 32 * 1024 * 1024

    /** Same configuration as [ModelJson], indented so the file is readable by humans. */
    private val prettyJson = Json(from = ModelJson) {
        prettyPrint = true
        prettyPrintIndent = "  "
    }

    fun encode(document: BackupDocument): String = prettyJson.encodeToString(BackupDocument.serializer(), document)

    /**
     * Parses [text]. Throws [InvalidBackupException] for anything that is not a well-formed Alarm Clock
     * backup and [UnsupportedBackupVersionException] for backups from a newer format version.
     */
    fun decode(text: String): BackupDocument {
        val root = try {
            ModelJson.parseToJsonElement(text)
        } catch (e: RuntimeException) {
            throw InvalidBackupException("The file is not JSON", e)
        }
        val obj = root as? JsonObject ?: throw InvalidBackupException("The backup root is not a JSON object")
        val format = (obj["format"] as? JsonPrimitive)?.takeIf { it.isString }?.content
        if (format != FORMAT) throw InvalidBackupException("Unknown backup format")
        val version = (obj["version"] as? JsonPrimitive)?.intOrNull
            ?: throw InvalidBackupException("The backup has no format version")
        if (version > VERSION) throw UnsupportedBackupVersionException(version, VERSION)
        if (version < 1) throw InvalidBackupException("Invalid backup format version $version")
        val document = try {
            ModelJson.decodeFromJsonElement(BackupDocument.serializer(), obj)
        } catch (e: RuntimeException) {
            // SerializationException, IllegalArgumentException from model init blocks, DateTimeException…
            throw InvalidBackupException("The backup content is damaged", e)
        }
        document.requireUniqueIds()
        return document
    }

    private fun BackupDocument.requireUniqueIds() {
        requireUnique("alarms", alarms.map { it.id })
        requireUnique("groups", groups.map { it.id })
        requireUnique("holidays", holidays.map { it.id })
        requireUnique("timers", timers.map { it.id })
        requireUnique("timerPresets", timerPresets.map { it.id })
        requireUnique("worldClocks", worldClocks.map { it.id })
        requireUnique("routineItems", routineItems.map { it.id })
        requireUnique("registeredCodes", registeredCodes.map { it.id })
        requireUnique("photoTargets", photoTargets.map { it.id })
        requireUnique("calendarRules", calendarRules.map { it.id })
        requireUnique("locationAlarms", locationAlarms.map { it.id })
    }

    /** Ids <= 0 mean "unsaved" and may repeat; saved ids must be unique within a section. */
    private fun requireUnique(section: String, ids: List<Long>) {
        val saved = ids.filter { it > 0L }
        if (saved.size != saved.toSet().size) throw InvalidBackupException("Duplicate ids in $section")
    }
}
